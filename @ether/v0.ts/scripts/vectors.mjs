function main() {
  const args = process.argv.slice(2);
  if (args.includes('--help') || args.includes('-h')) { console.log(usage); return; }
  const check = args.includes('--check');
  const differing = [];
  for (const [path, make] of Object.entries(generated)) {
    const text = make();
    const at = join(ether, path);
    const committed = existsSync(at) ? readFileSync(at, 'utf8') : undefined;
    if (check) {
      if (committed !== text) differing.push(path);
      console.log(`${path.padEnd(44)} ${committed === text ? 'same' : committed === undefined ? 'MISSING' : 'DIFFERS'}`);
    } else {
      if (committed !== text) writeFileSync(at, text);
      console.log(`${path.padEnd(44)} ${committed === text ? 'unchanged' : 'written'}`);
    }
  }
  if (differing.length > 0) {
    console.log(`\n${differing.length} generated files differ from what the reference implementations give now; run node scripts/vectors.mjs and review the change.`);
    process.exit(1);
  }
}

main();
